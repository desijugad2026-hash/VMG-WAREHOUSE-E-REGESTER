  suspend fun seedIfNeeded(repository: WarehouseRepository) {
    // 1. Ensure all 80 Debtors from DEBTORS.png exist
    val existingCreditors = repository.creditors.first()
    val existingDebtorNames = existingCreditors.map { it.name.trim().lowercase() }.toSet()
    val missingDebtors = INITIAL_DEBTORS.filter { it.name.trim().lowercase() !in existingDebtorNames }
    if (missingDebtors.isNotEmpty()) {
      repository.insertAllCreditors(missingDebtors)
    }

    // 2. Ensure all 346 Tiles from the 7 Tile sheets exist (keyed by size + designName)
    val existingCatalog = repository.catalogItems.first()
    val existingTileKeys = existingCatalog.map { "${it.size.trim().lowercase()}|${it.designName.trim().lowercase()}" }.toSet()
    val missingTiles = INITIAL_TILES.filter {
      "${it.size.trim().lowercase()}|${it.designName.trim().lowercase()}" !in existingTileKeys
    }
    if (missingTiles.isNotEmpty()) {
      repository.insertAllCatalogItems(missingTiles)
    }
  }
